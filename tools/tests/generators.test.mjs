test("flattens and resolves token aliases", () => {
  const flat = flatten({
    color: { base: "#fff" },
    surface: { base: "{color.base}" },
  });
  assert.deepEqual(resolveAliases(flat), {
    "color.base": "#fff",
    "surface.base": "#fff",
  });
});

