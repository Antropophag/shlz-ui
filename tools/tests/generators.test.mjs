test("normalizes only known monochrome paints", () => {
  assert.match(
    normalizeMonochromeSvg('<svg><path fill="#0B1623"/></svg>'),
    /currentColor/,
  );
  assert.match(
    normalizeMonochromeSvg('<svg><path fill="#CC1F1F"/></svg>'),
    /#CC1F1F/,
  );
});

test("production icons are generated byte-for-byte from normalized corpus", async () => {
  const manifest = await json("packages/icons/dist/manifest.json");
  const normalized = await json("packages/icons/normalized/manifest.json");
  assert.equal(manifest.length, 119);
  assert.equal(
    manifest.reduce((count, icon) => count + icon.variants.length, 0),
    125,
  );
  for (const icon of manifest) {
    const source = normalized.find(({ name }) => name === icon.name);
    assert.ok(source, `Missing normalized source for ${icon.name}`);
    assert.equal(
      await readFile(`packages/icons/dist/${icon.file}`, "utf8"),
      await readFile(
        `packages/icons/normalized/${source.normalizedPath}`,
        "utf8",
      ),
    );
    for (const variant of icon.variants) {
      const normalizedVariant = source.variants.find(
        ({ normalizedPath }) => normalizedPath === variant.normalizedPath,
      );
      assert.ok(normalizedVariant);
      assert.equal(
        await readFile(`packages/icons/dist/${variant.file}`, "utf8"),
        await readFile(
          `packages/icons/normalized/${variant.normalizedPath}`,
          "utf8",
        ),
      );
      assert.equal(variant.geometrySha256, normalizedVariant.geometrySha256);
    }
  }
  assert.equal(manifest.filter(({ currentColor }) => currentColor).length, 97);
  assert.equal(manifest.filter(({ currentColor }) => !currentColor).length, 22);
});

test("compatibility aliases resolve to normalized production SVGs", async () => {
  const aliases = await json("packages/icons/dist/compatibility-aliases.json");
  const manifest = await json("packages/icons/dist/manifest.json");
  assert.equal(aliases.length, 42);
  assert.equal(new Set(aliases.map(({ alias }) => alias)).size, aliases.length);
  assert.ok(!manifest.some(({ name }) => name === "search-bold"));
  for (const alias of aliases) {
    const target = manifest.find(({ name }) => name === alias.target);
    const variant = target?.variants.find(({ name }) => name === alias.variant);
    assert.ok(variant, `Missing alias target for ${alias.alias}`);
    assert.equal(
      await readFile(`packages/icons/dist/${alias.file}`, "utf8"),
      await readFile(`packages/icons/dist/${variant.file}`, "utf8"),
    );
  }
});

