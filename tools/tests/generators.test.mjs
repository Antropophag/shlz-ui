test("sprite symbols retain root paint defaults, definitions, and scoped references", async () => {
  const sprite = await readFile("packages/icons/dist/sprite.svg", "utf8");
  const normalized = await json("packages/icons/normalized/manifest.json");
  for (const icon of normalized) {
    for (const variant of icon.variants) {
      const name = variant.normalizedPath
        .split("/")
        .pop()
        .replace(/\.svg$/, "");
      const svg = await readFile(
        `packages/icons/normalized/${variant.normalizedPath}`,
        "utf8",
      );
      const rootFill = svg.match(/<svg\b[^>]*\bfill=["']([^"']+)["']/)?.[1];
      const symbol = sprite.match(
        new RegExp(`<symbol id="shlz-icon-${name}"[\\s\\S]*?<\\/symbol>`),
      )?.[0];
      assert.ok(symbol, `missing symbol ${name}`);
      if (rootFill !== undefined)
        assert.match(symbol, new RegExp(`\\bfill="${rootFill}"`));
      if (svg.includes("<defs")) {
        assert.match(symbol, /<defs/);
        assert.doesNotMatch(symbol, /url\(#clip/);
        assert.match(symbol, new RegExp(`url\\(#shlz-icon-${name}-`));
      }
    }
  }
});

test("production icon generation is deterministic", async () => {
  const files = [
    "packages/icons/dist/manifest.json",
    "packages/icons/dist/compatibility-aliases.json",
    "packages/icons/dist/sprite.svg",
    "packages/icons/dist/index.js",
    "packages/icons/dist/index.d.ts",
  ];
  const before = await Promise.all(files.map((file) => readFile(file, "utf8")));
  await execFileAsync(process.execPath, ["tools/generate.mjs"]);
  const after = await Promise.all(files.map((file) => readFile(file, "utf8")));
  assert.deepEqual(after, before);
});

test("source references are deterministic raw SVG fixtures", async () => {
  const before = await generateSourceReferences();
  const first = await readFile(
    "apps/showcase/generated/source-references/tooltip.svg",
    "utf8",
  );
  const after = await generateSourceReferences();
  const second = await readFile(
    "apps/showcase/generated/source-references/tooltip.svg",
    "utf8",
  );
  assert.deepEqual(after, before);
  assert.equal(second, first);
  assert.match(first, /viewBox="0 440 572 330"/);
  assert.match(first, /clip8_145_26864/);
  assert.ok(before.length >= 21);
  for (const component of [
    "checkbox",
    "radio",
    "switch",
    "badge-count",
    "badge-dot",
    "status-requests",
    "status-details",
  ]) {
    assert.ok(before.some((entry) => entry.component === component));
  }
  const tooltip = before.find(({ component }) => component === "tooltip");
  assert.equal(tooltip.originalViewBox, "0 0 572 770");
  assert.match(tooltip.sourceSha256, /^[a-f0-9]{64}$/);
  assert.equal(tooltip.references[0].cropViewBox, "0 440 572 330");
  assert.match(tooltip.references[0].reason, /component matrix/);
});
